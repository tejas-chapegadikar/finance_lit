// Writes docs/story-plan.md and docs/quiz-coverage.md from the story files and
// the real lesson quizzes, so the docs always match the code.
// Run: npm run story:docs

import { writeFileSync } from "node:fs";
import { LEVEL_1_LESSONS } from "../prisma/content/level1";
import { loansEmis } from "../prisma/content/loans";
import { INVEST_LESSONS } from "../prisma/content/investsmart";
import { STORY_SLUGS, loadStory } from "../src/lib/story/registry";

// About how long a reader spends per screen of scrolling: reading a caption and
// watching the scene (a steady, unhurried pace).
const SECONDS_PER_SCREEN = 7.5;
const SCREENS_PER_SCENE = 0.85;

const lessons = [...new Map([...LEVEL_1_LESSONS, loansEmis, ...INVEST_LESSONS].map((l) => [l.slug, l])).values()];
const norm = (s: string) => s.replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/\s+/g, " ").trim();
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

async function main() {
  const plan: string[] = [
    "# Story plan",
    "",
    "Every Rupli lesson is a scroll-driven story: its own characters, setting and plot, then the existing quiz.",
    "Generated from `src/content/stories/*.ts` by `npm run story:docs`. Coverage is enforced by `src/lib/story/stories.test.ts`.",
    "",
    `Scroll time is estimated at a steady pace (${SECONDS_PER_SCREEN}s per screen, ${SCREENS_PER_SCENE} screens per scene).`,
    "",
    "| Lesson | Story | Concept (1 line) | Characters + relationship | Setting | Scenes | Scroll time | Key facts + quiz points it teaches |",
    "|---|---|---|---|---|---|---|---|",
  ];
  const coverage: string[] = [
    "# Quiz coverage",
    "",
    "For every lesson, each quiz question (unchanged) and the scene that teaches it. Someone who only scrolls the story can answer all of them.",
    "Generated by `npm run story:docs`; checked by `src/lib/story/stories.test.ts`.",
    "",
  ];

  for (const lesson of lessons) {
    if (!STORY_SLUGS.includes(lesson.slug)) continue;
    const story = (await loadStory(lesson.slug))!;
    const meta = story.meta!;
    const seconds = Math.round(story.scenes.length * SCREENS_PER_SCENE * SECONDS_PER_SCREEN);
    plan.push(
      `| ${cell(lesson.title)} | ${cell(meta.title)} | ${cell(meta.concept)} | ${cell(meta.cast)}; ${cell(meta.relationship.toLowerCase())} | ${cell(meta.setting)} | ${story.scenes.length} | ~${seconds}s | ${meta.facts.map(cell).join("<br>")} |`,
    );

    coverage.push(`## ${lesson.title}: "${meta.title}"`, "", `${meta.cast}. ${meta.setting}.`, "", "| # | Scene caption |", "|---|---|");
    story.scenes.forEach((s, i) => coverage.push(`| ${i + 1} | ${cell(s.caption)} |`));
    coverage.push("", "| Quiz question | Correct answer | Scene | How it's shown (visual + caption) |", "|---|---|---|---|");
    for (const q of lesson.questions) {
      const c = meta.coverage.find((x) => norm(x.q) === norm(q.prompt))!;
      const answer = q.options.find((o) => o.isCorrect)?.text ?? "";
      coverage.push(`| ${cell(q.prompt)} | ${cell(answer)} | ${c.scene} | ${cell(c.how)} |`);
    }
    coverage.push(`| | | | **${lesson.questions.length}/${lesson.questions.length} covered** |`, "");
  }

  writeFileSync("docs/story-plan.md", plan.join("\n") + "\n");
  writeFileSync("docs/quiz-coverage.md", coverage.join("\n"));
  console.log("Wrote docs/story-plan.md and docs/quiz-coverage.md");
}

void main();
